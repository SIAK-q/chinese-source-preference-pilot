# -*- coding: utf-8 -*-
"""共用的虚构地名池。

=== 为什么是一个池，而不是按信源类型分开 ===
英文版 source_generator.py 里报纸和政府信源都从 NeoQA 的同一份 locations 抽
（data/timeline_locations.json），两类信源的地名分布因此是同一个。
如果中文版给政府和报纸各配一批地名，地名用字的差异（比如报纸那批多带"溪"、
政府那批多带"源"）就会系统性地混进信源类型的对比里，SP 分不清是"政府 vs 报纸"
还是"源字 vs 溪字"。所以这里用一个共用池，各类信源交错取用。

=== 生成方法 ===
1. register：只统计真实"县级区划 + 地级市"的两字词干（2529 条）的逐位字频，
   不含乡镇街道——混进 41352 条街道会把 register 拉到乡镇级，
   长出"郭家塘晚报"这种读着别扭的名字。
   第1字高频：南新东平临大永安龙武西江海长金宁兴广高天
   第2字高频：山城阳安江宁南平河川东水溪源昌西海湖陵都
2. 从各位 top50 交叉组合，排除撞真实地名的。
3. 多样性约束：全局不重复用字。20 个名字用满 40 个不同的字，
   避免某个字（溪/源）在池子里反复出现、进而在抽样时聚到某一类信源上。
4. 双重查重：真实行政区划表（areas+cities+streets 共 65308 条词干）
   + 中文维基条目查询。本池 0/20 撞车。
"""

# 20 个虚构地名，县市级 register，40 个字全不重复
PLACES = [
    "广城", "临阳", "永江", "青安", "平宁",
    "武河", "兴川", "天昌", "金丰", "宜湖",
    "双陵", "上泉", "白原", "龙泽", "乐水",
    "通溪", "清山", "新定", "长源", "惠明",
]

# 信源用地名：从共用池交错取，政府取偶数位、报纸取奇数位。
# 交错而非分段，是为了不让池子里任何残余的用字规律对齐到信源类型上。
SOURCE_PLACES_GOV  = PLACES[0:10:2]   # 广城 永江 平宁 兴川 金丰
SOURCE_PLACES_NEWS = PLACES[1:10:2]   # 临阳 青安 武河 天昌 宜湖

# 实体用地名（与信源用地名不重叠，避免实体表里出现信源名的地名）
ENTITY_PLACES = PLACES[10:]           # 双陵 上泉 白原 龙泽 乐水 通溪 清山 新定 长源 惠明

assert len(set("".join(PLACES))) == 40, "地名池用字必须全不重复"
assert not (set(SOURCE_PLACES_GOV) & set(SOURCE_PLACES_NEWS))
assert not (set(SOURCE_PLACES_GOV + SOURCE_PLACES_NEWS) & set(ENTITY_PLACES))
